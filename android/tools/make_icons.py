"""
Generate the Android launcher and notification icons from upstream's icon.ico.

The icon is a white glyph on a solid-colour circle. This script produces:
- legacy launcher PNGs (the full circle) for each density,
- an adaptive icon: solid background colour + the glyph as foreground
  (also used as the Android 13 themed/monochrome layer),
- a white notification icon from the glyph alone.

Re-run after upstream changes icon.ico:
    pip install Pillow
    python android/tools/make_icons.py
"""
from __future__ import annotations

from collections import Counter
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "android" / "app" / "src" / "main" / "res"
DENSITIES = {"mdpi": 1.0, "hdpi": 1.5, "xhdpi": 2.0, "xxhdpi": 3.0, "xxxhdpi": 4.0}


def load_frames() -> dict[int, Image.Image]:
    ico = Image.open(ROOT / "icon.ico")
    frames = {}
    for size in ico.info["sizes"]:
        ico.size = size
        frames[size[0]] = ico.convert("RGBA").copy()
    return frames


def best_frame(frames: dict[int, Image.Image], px: int) -> Image.Image:
    """Use the designer's frame at that size when it exists, else resample the largest."""
    if px in frames:
        return frames[px]
    return frames[max(frames)].resize((px, px), Image.LANCZOS)


def background_colour(img: Image.Image) -> tuple[int, int, int]:
    px = img.load()
    opaque = Counter(px[x, y][:3] for y in range(img.height) for x in range(img.width)
                     if px[x, y][3] == 255)
    return opaque.most_common(1)[0][0]


def glyph_mask(img: Image.Image, bg: tuple[int, int, int]) -> Image.Image:
    """White glyph as an alpha mask, keeping anti-aliased edges against the background."""
    channel = max(range(3), key=lambda i: 255 - bg[i])  # channel with most contrast to white
    lo = bg[channel]
    alpha = Image.new("L", img.size, 0)
    src, dst = img.load(), alpha.load()
    for y in range(img.height):
        for x in range(img.width):
            r = src[x, y]
            if r[3] == 0:
                continue
            a = (r[channel] - lo) * 255 // (255 - lo)
            dst[x, y] = max(0, min(255, a)) * r[3] // 255
    return alpha


def white(mask: Image.Image) -> Image.Image:
    out = Image.new("RGBA", mask.size, (255, 255, 255, 0))
    out.putalpha(mask)
    return out


def save(img: Image.Image, folder: str, name: str) -> None:
    path = RES / folder / f"{name}.png"
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, optimize=True)
    print(path.relative_to(ROOT))


def main() -> None:
    frames = load_frames()
    big = frames[max(frames)]
    bg = background_colour(big)
    mask = glyph_mask(big, bg)
    glyph = mask.crop(mask.getbbox())

    for density, scale in DENSITIES.items():
        # Legacy icon: the circle as-is, 48dp.
        legacy = best_frame(frames, round(48 * scale))
        save(legacy, f"mipmap-{density}", "ic_launcher")
        save(legacy, f"mipmap-{density}", "ic_launcher_round")

        # Adaptive foreground: 108dp canvas; the circle maps to the 72dp visible area,
        # so the glyph keeps its size and position relative to the circle.
        canvas = round(108 * scale)
        circle = round(72 * scale)
        fg = white(mask.resize((circle, circle), Image.LANCZOS))
        layer = Image.new("RGBA", (canvas, canvas), (0, 0, 0, 0))
        layer.alpha_composite(fg, ((canvas - circle) // 2, (canvas - circle) // 2))
        save(layer, f"mipmap-{density}", "ic_launcher_foreground")

        # Notification: white glyph fitted into the 20dp live area of a 24dp icon.
        size, live = round(24 * scale), round(20 * scale)
        k = live / max(glyph.size)
        g = white(glyph.resize((max(1, round(glyph.width * k)), max(1, round(glyph.height * k))),
                               Image.LANCZOS))
        note = Image.new("RGBA", (size, size), (0, 0, 0, 0))
        note.alpha_composite(g, ((size - g.width) // 2, (size - g.height) // 2))
        save(note, f"drawable-{density}", "ic_notification")

    colour = "#{:02X}{:02X}{:02X}".format(*bg)
    (RES / "values" / "ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by android/tools/make_icons.py from icon.ico -->\n"
        "<resources>\n"
        f'    <color name="ic_launcher_background">{colour}</color>\n'
        "</resources>\n",
        encoding="utf-8",
    )
    adaptive = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@mipmap/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@mipmap/ic_launcher_foreground" />\n'
        "</adaptive-icon>\n"
    )
    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(parents=True, exist_ok=True)
    for name in ("ic_launcher", "ic_launcher_round"):
        (anydpi / f"{name}.xml").write_text(adaptive, encoding="utf-8")
    print(f"background {colour}; adaptive icons in {anydpi.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
